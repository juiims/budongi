def safe_int(v):
    if not v:
        return None
    s = str(v).rstrip("%").strip()
    try:
        return int(s)
    except (ValueError, TypeError):
        return None


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "data/regional_summary_dong.csv"
    print(f"비교 대상: {target}")
    print(f"기준값: 2026.04 스크린샷\n")
    with open(target, encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))

    # 표 헤더
    print(f"{'지역':<8}", end="")
    for c in COLS:
        print(f"{c:>10}", end="")
    print()
    print("-" * 124)

    deltas_per_col = {c: [] for c in COLS}
    for r in rows:
        name = r["지역"]
        if name not in SCREENSHOT:
            continue
        screen = SCREENSHOT[name]
        ours = [safe_int(r.get(c)) for c in COLS]
        print(f"{name:<8}", end="")
        for col_i, (o, s) in enumerate(zip(ours, screen)):
            if o is None:
                print(f"{'-':>10}", end="")
                continue
            col_name = COLS[col_i]
            if col_name == "전세가율":
                d = o - s
                deltas_per_col[col_name].append(abs(d))
                print(f" {d:+4}%p({o:>2})", end="")
            else:
                d = (o - s) / s * 100 if s else 0
                deltas_per_col[col_name].append(abs(d))
                print(f" {d:+6.1f}%", end="")
        print()

    print("-" * 124)
    print(f"{'평균 |Δ|':<8}", end="")
    for c in COLS:
        ds = deltas_per_col[c]
        if not ds:
            print(f"{'-':>10}", end="")
            continue
        avg = sum(ds) / len(ds)
        unit = "%p" if c == "전세가율" else "%"
        print(f" ±{avg:>5.1f}{unit:<2}", end="")
    print("\n")


if __name__ == "__main__":
    main()
